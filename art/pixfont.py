GLYPHS: dict[str, list[str]] = {}
for _line in _GLYPHS_SRC.strip().splitlines():
    _ch, *_rows = _line.split(" ")
    GLYPHS[_ch] = _rows

_NARROW = set(".,:-/+!()'<>*")


def _columns(ch: str) -> range:
    rows = GLYPHS[ch]
    if ch not in _NARROW:
        return range(5)
    used = [x for x in range(5) if any(r[x] == "#" for r in rows)]
    return range(min(used), max(used) + 1)


def text_width(text: str, spacing: int = 1) -> int:
    width = 0
    for ch in text.upper():
        width += 3 if ch == " " else len(_columns(ch))
        width += spacing
    return max(0, width - spacing)


def render(text: str, color: str = "hud_text", spacing: int = 1, shadow: str | None = None) -> Image.Image:
    """Render text into a tight RGBA image. Lowercase is drawn as uppercase, and * is a times sign."""
    text = text.upper()
    w = text_width(text, spacing) + (1 if shadow else 0)
    h = 7 + (1 if shadow else 0)
    img = Image.new("RGBA", (max(1, w), h), (0, 0, 0, 0))
    px = img.load()
    layers = ([(shadow, 1)] if shadow else []) + [(color, 0)]
    for col, off in layers:
        x = 0
        c = rgba(col)
        for ch in text:
            if ch == " ":
                x += 3 + spacing
                continue
            cols = _columns(ch)
            for gy, row in enumerate(GLYPHS[ch]):
                for i, gx in enumerate(cols):
                    if row[gx] == "#":
                        px[x + i + off, gy + off] = c
            x += len(cols) + spacing
    return img
